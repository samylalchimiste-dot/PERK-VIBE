export function getCitiesForDepartment(deptCodeOrName: string): string[] {
  const clean = deptCodeOrName.toLowerCase();
  const found = FRENCH_DEPARTMENTS.find(d => 
    clean.includes(d.code.toLowerCase()) || 
    clean.includes(d.name.toLowerCase()) ||
    (d.code === '75' && clean.includes('paris'))
  );
  return found ? found.popularCities : POPULAR_FRENCH_CITIES.slice(0, 15);
}
